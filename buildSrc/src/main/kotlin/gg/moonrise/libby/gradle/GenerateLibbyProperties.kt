package gg.moonrise.libby.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates the `gg.moonrise.libby.LibbyProperties` source file holding build constants.
 */
@CacheableTask
abstract class GenerateLibbyProperties : DefaultTask() {
    /** The project version written to `LibbyProperties.VERSION`. */
    @get:Input
    abstract val libbyVersion: Property<String>

    /** The source root the generated file is written to. */
    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val version = libbyVersion.get()
        require(version.none { it == '"' || it == '\\' || it.isISOControl() }) { "Unsupported version string: $version" }

        val root = outputDirectory.get().asFile
        root.deleteRecursively()
        val file = root.resolve("gg/moonrise/libby/LibbyProperties.java")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package gg.moonrise.libby;
            |
            |/**
            | * Build-time constants generated by the libby build.
            | */
            |public final class LibbyProperties {
            |    /**
            |     * Project version
            |     */
            |    public static final String VERSION = "$version";
            |
            |    /**
            |     * User agent string to use when downloading libraries
            |     */
            |    public static final String HTTP_USER_AGENT = "libby/" + VERSION;
            |
            |    private LibbyProperties() {
            |    }
            |}
            |""".trimMargin(),
        )
    }
}
